package edu.course.lab01;

public class TextTasks //Объявление класса для текстовых задач (разворот и палиндром)
{

    public static void reverse(String text) //Метод, принимающий строку для выполнения её разворота
    {
        for (int i = text.length() - 1; i >= 0; i--) //Цикл, идущий от последнего символа строки к нулевому (задом наперед)
        {
            System.out.print(text.charAt(i)); //Извлечение символа по индексу i и вывод его в консоль без переноса строки
        }
        System.out.println(); //Печать пустого переноса строки после того, как все символы выведены
    }

    public static void palindrome(String text) //Метод для проверки, является ли переданная строка палиндромом
    {
        int left = 0; //Создание указателя (индекса) на начало строки
        int right = text.length() - 1; //Создание указателя (индекса) на конец строки

        while (left < right) //Выполнение цикла, пока левый указатель не встретится с правым или не перейдет за него
        {
            char charLeft = text.charAt(left); //Извлечение символа под левым указателем
            char charRight = text.charAt(right); //Извлечение символа под правым указателем

            if (!Character.isLetterOrDigit(charLeft)) //Проверка, является ли левый символ знаком препинания или пробелом
            {
                left++; //Если это не буква и не цифра, сдвигаем левый указатель на шаг вправо (пропускаем символ)
            }
            else if (!Character.isLetterOrDigit(charRight)) //Проверка, является ли правый символ знаком препинания или пробелом
            {
                right--; //Если это не буква и не цифра, сдвигаем правый указатель на шаг влево (пропускаем символ)
            }
            else //Если оба символа (слева и справа) являются буквами или цифрами
            {
                if (Character.toLowerCase(charLeft) != Character.toLowerCase(charRight)) //Сравниваем их, предварительно переведя в нижний регистр для игнорирования регистра
                {
                    System.out.println("false"); //Если символы не совпали, то строка не палиндром, выводим "false"
                    return; //Немедленно завершаем выполнение метода
                }
                left++; //Если символы совпали, сдвигаем левый указатель вправо для проверки следующей пары
                right--; //И сдвигаем правый указатель влево
            }
        }
        System.out.println("true"); //Если цикл завершил работу полностью, значит несовпадений не найдено — выводим "true"
    }
}