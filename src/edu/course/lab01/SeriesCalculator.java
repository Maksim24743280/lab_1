package edu.course.lab01;

public class SeriesCalculator //Объявление класса для подсчета суммы бесконечного ряда
{
    public static void calculate() //Метод запуска процесса вычисления
    {
        double sum = 0.0; //Создание переменной типа double для хранения накопленной суммы ряда
        int n = 2; //Создание переменной n, задающей начальный номер (индекс) члена ряда, равный 2 по условию
        int count = 0; //Создание счетчика количества членов ряда, которые были добавлены к сумме

        while (true) //Запуск бесконечного цикла (выход из него будет осуществлен программно через условие)
        {
            double term = 1.0 / (n * n + n - 2); //Вычисление значения текущего члена ряда по формуле из задания

            if (Math.abs(term) < 1e-6) //Проверка условия выхода: если абсолютное значение члена ряда (модуль) стало меньше одной миллионной
            {
                break; //Прерываем бесконечный цикл (не добавляя этот член к сумме)
            }

            sum += term; //Прибавляем вычисленный член ряда к общей сумме
            count++; //Увеличиваем счетчик добавленных элементов на единицу
            n++; //Увеличиваем индекс n на единицу для следующей итерации цикла
        }

        int lastAddedN = n - 1; //Так как в конце последней успешной итерации 'n' было увеличено на 1, последний добавленный индекс равен n - 1

        System.out.println("Вычисленная сумма: " + sum);
        System.out.println("Последний добавленный номер n: " + lastAddedN);
        System.out.println("Количество добавленных членов ряда: " + count);
    }
}